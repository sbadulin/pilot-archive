// Regenerates functions/api/_lib/baseCatalog.ts from the archive catalog.
// Run after changing archive-catalog/manifest.json; tests/manifest.test.ts fails when the two drift.
import { readFile, writeFile } from 'node:fs/promises';

const manifest = JSON.parse(await readFile('archive-catalog/manifest.json', 'utf8'));
const issues = manifest.issues ?? [];
if (!Array.isArray(issues) || issues.length === 0) throw new Error('Archive catalog is empty');
const body = issues.map(issue => `  ${JSON.stringify(issue)},`).join('\n');
await writeFile(
  'functions/api/_lib/baseCatalog.ts',
  `import type { CatalogIssue } from './manifest';\n\n// Generated by scripts/generate-base-catalog.mjs from archive-catalog/manifest.json.\n// The archive migrated to Selectel before the admin panel existed; it is not in D1.\nexport const baseCatalog: CatalogIssue[] = [\n${body}\n];\n`,
);
console.log(`Wrote base catalog with ${issues.length} issues.`);
